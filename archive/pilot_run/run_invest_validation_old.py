import os
import json
import argparse
from pathlib import Path
from typing import Dict, Any, Optional
from pydantic import BaseModel, Field
import anthropic
from json_repair import repair_json

# ---------------------------------------------------------------------------
# Pydantic Schema Definitions with Robust Fallbacks
# ---------------------------------------------------------------------------
class InvestCriterionResult(BaseModel):
    passed: bool = Field(default=False, description="True if requirement satisfies criterion, False if violated.")
    rationale: str = Field(default="Not evaluated or omitted by aggregator.", description="Detailed explanation of the verdict.")
    recommendation: Optional[str] = Field(None, description="Actionable suggestion for improvement if failed.")

class InvestValidationResult(BaseModel):
    requirement_id: str
    independent: Optional[InvestCriterionResult] = Field(default_factory=lambda: InvestCriterionResult(passed=False, rationale="Default fallback: missing from aggregator response."))
    negotiable: Optional[InvestCriterionResult] = Field(default_factory=lambda: InvestCriterionResult(passed=False, rationale="Default fallback: missing from aggregator response."))
    valuable: Optional[InvestCriterionResult] = Field(default_factory=lambda: InvestCriterionResult(passed=False, rationale="Default fallback: missing from aggregator response."))
    estimable: Optional[InvestCriterionResult] = Field(default_factory=lambda: InvestCriterionResult(passed=False, rationale="Default fallback: missing from aggregator response."))
    small: Optional[InvestCriterionResult] = Field(default_factory=lambda: InvestCriterionResult(passed=False, rationale="Default fallback: missing from aggregator response."))
    testable: Optional[InvestCriterionResult] = Field(default_factory=lambda: InvestCriterionResult(passed=False, rationale="Default fallback: missing from aggregator response."))

# ---------------------------------------------------------------------------
# Agentic System Prompt Definitions
# ---------------------------------------------------------------------------
META_PROMPTER_SYSTEM = """You are a Lead Requirements Engineer and Meta-Prompter.
Your task is to analyze the domain context of a given software requirement and generate specific evaluation guardrails for auditing it against the INVEST criteria.
"""

DRAFTER_SYSTEM = """You are an Expert Requirements Quality Auditor (Drafter Agent).
Conduct an in-depth initial review of a given software requirement against the 6 INVEST criteria.
"""

REVIEWER_SYSTEM = """You are a Senior Quality Assurance Architect (Reviewer Agent).
Critically review the initial analysis generated by the Drafter Agent and deliver a balanced consensus review.
"""

AGGREGATOR_SYSTEM = """You are an Evaluator-Aggregator Agent.
Synthesize the Drafter's assessment and Reviewer's critique into a finalized verdict.
You MUST output strictly formatted JSON conforming to the requested schema, ensuring all 6 criteria (independent, negotiable, valuable, estimable, small, testable) are present.
"""

# ---------------------------------------------------------------------------
# Multi-Agent Orchestrator Pipeline
# ---------------------------------------------------------------------------
class MultiAgentInvestPipeline:
    def __init__(self, api_key: Optional[str] = None, model_name: str = "claude-sonnet-5"):
        self.client = anthropic.Anthropic(api_key=api_key or os.environ.get("ANTHROPIC_API_KEY"))
        self.model_name = model_name
        self.total_input_tokens = 0
        self.total_output_tokens = 0

    def _extract_text(self, response) -> str:
        """Extracts text content blocks, ignoring thinking blocks if present."""
        extracted_texts = []
        for block in response.content:
            if hasattr(block, "text") and block.text:
                extracted_texts.append(block.text)
            elif isinstance(block, dict) and block.get("type") == "text":
                extracted_texts.append(block.get("text", ""))
        
        if extracted_texts:
            return "\n".join(extracted_texts)
        
        # Fallback string representation if structure differs
        return str(response.content)

    def _track_usage(self, response):
        if hasattr(response, "usage") and response.usage:
            self.total_input_tokens += getattr(response.usage, "input_tokens", 0)
            self.total_output_tokens += getattr(response.usage, "output_tokens", 0)

    def run_meta_prompter(self, req_id: str, text: str, domain: str) -> str:
        prompt = f"Requirement ID: {req_id}\nDomain Context: {domain}\nRequirement Text: {text}\n\nGenerate domain-tailored evaluation guardrails."
        response = self.client.messages.create(
            model=self.model_name, max_tokens=2048, system=META_PROMPTER_SYSTEM,
            messages=[{"role": "user", "content": prompt}]
        )
        self._track_usage(response)
        return self._extract_text(response)

    def run_drafter(self, req_id: str, text: str, domain_guardrails: str) -> str:
        prompt = f"Requirement ID: {req_id}\nRequirement Text: {text}\n\nDomain Guardrails:\n{domain_guardrails}\n\nProvide initial INVEST audit."
        response = self.client.messages.create(
            model=self.model_name, max_tokens=4096, system=DRAFTER_SYSTEM,
            messages=[{"role": "user", "content": prompt}]
        )
        self._track_usage(response)
        return self._extract_text(response)

    def run_reviewer(self, req_id: str, text: str, draft_assessment: str) -> str:
        prompt = f"Requirement ID: {req_id}\nRequirement Text: {text}\n\nDrafter Assessment:\n{draft_assessment}\n\nCritique and refine."
        response = self.client.messages.create(
            model=self.model_name, max_tokens=4096, system=REVIEWER_SYSTEM,
            messages=[{"role": "user", "content": prompt}]
        )
        self._track_usage(response)
        return self._extract_text(response)

    def run_aggregator(self, req_id: str, text: str, draft_assessment: str, reviewer_critique: str) -> Dict[str, Any]:
        prompt = f"""Requirement ID: {req_id}
Requirement Text: {text}

Drafter Assessment:
{draft_assessment}

Reviewer Critique:
{reviewer_critique}

Synthesize the final evaluation across all 6 INVEST criteria.
Respond ONLY with a valid JSON object matching this schema structure:
{{
  "requirement_id": "{req_id}",
  "independent": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "negotiable": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "valuable": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "estimable": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "small": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "testable": {{"passed": true, "rationale": "...", "recommendation": "..."}}
}}
"""
        response = self.client.messages.create(
            model=self.model_name, max_tokens=4096, system=AGGREGATOR_SYSTEM,
            messages=[{"role": "user", "content": prompt}]
        )
        self._track_usage(response)
        
        raw_json_str = self._extract_text(response)
        if "```" in raw_json_str:
            raw_json_str = raw_json_str.split("```json")[-1].split("```")[0].strip()
            if not raw_json_str.startswith("{"):
                parts = raw_json_str.split("```")
                for p in parts:
                    if "{" in p and "}" in p:
                        raw_json_str = p.strip()
                        break
        
        repaired_json_str = repair_json(raw_json_str, return_objects=False)
        parsed_dict = json.loads(repaired_json_str)

        validated_schema = InvestValidationResult(**parsed_dict)
        return validated_schema.model_dump()

    def validate_requirement(self, req: Dict[str, Any]) -> Dict[str, Any]:
        req_id = req.get("requirement_id", req.get("id", "UNKNOWN"))
        text = req.get("text_clean", req.get("text", ""))
        domain = req.get("domain", "General Software Engineering")

        domain_guardrails = self.run_meta_prompter(req_id, text, domain)
        draft_assessment = self.run_drafter(req_id, text, domain_guardrails)
        reviewer_critique = self.run_reviewer(req_id, text, draft_assessment)
        final_validation = self.run_aggregator(req_id, text, draft_assessment, reviewer_critique)

        req_copy = dict(req)
        req_copy["invest_validation"] = final_validation
        req_copy["agent_traces"] = {
            "meta_guardrails": domain_guardrails,
            "drafter_notes": draft_assessment,
            "reviewer_notes": reviewer_critique
        }
        return req_copy

def main():
    parser = argparse.ArgumentParser(description="Multi-Agent INVEST Requirements Validation Pipeline")
    parser.add_argument("--input", default="data/processed/thesis_50_validated.json", help="Path to input requirements JSON file")
    parser.add_argument("--output", default="data/processed/thesis_50_validated.json", help="Path to save processed results")
    parser.add_argument("--limit", type=int, default=None, help="Limit execution to N requirements for testing")
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    if not input_path.exists():
        print(f"Error: Input file {input_path} not found.")
        return

    with open(input_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if args.limit:
        data = data[:args.limit]

    print("==================================================")
    print("  AI-NATIVE MULTI-AGENT VALIDATION PIPELINE       ")
    print("  Roles: Meta-Prompter -> Drafter -> Reviewer -> Aggregator")
    print("==================================================")
    print(f"Processing {len(data)} requirements using model 'claude-sonnet-5'...\n")

    pipeline = MultiAgentInvestPipeline()
    validated_dataset = []

    for idx, req in enumerate(data, 1):
        req_id = req.get("requirement_id", req.get("id", f"REQ_{idx}"))
        print(f"[{idx}/{len(data)}] Executing multi-agent validation for {req_id}...")
        try:
            result = pipeline.validate_requirement(req)
            validated_dataset.append(result)
            print(f"   └─ SUCCESS: Evaluated across all 6 INVEST dimensions.")
        except Exception as e:
            print(f"   └─ ERROR processing {req_id}: {str(e)}")
            validated_dataset.append(req)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(validated_dataset, f, indent=2)

    print("\n==================================================")
    print(f" Multi-Agent processing complete!")
    print(f" Total Token Usage -> Input: {pipeline.total_input_tokens:,} | Output: {pipeline.total_output_tokens:,}")
    print(f" Saved serialized multi-agent results to {output_path}")
    print("==================================================")

if __name__ == "__main__":
    main()
