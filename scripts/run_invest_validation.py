"""Multi-agent INVEST review: Meta-Prompter -> Drafter -> Reviewer -> Evaluator-Aggregator.

The four agent prompts are unchanged from the version used in the first
production run. Fixes in this version (see llm_common.py):
  * reads the clean requirements file by default and never overwrites its input;
  * no silent fallbacks, retries on empty replies, per-record status;
  * --no-meta-prompter: replaces the Meta-Prompter with fixed, generic INVEST
    guardrails (the ablation condition for RQ2);
  * optional --temperature; every run is written to data/logs/runs.jsonl.

Usage
    python scripts/run_invest_validation.py --output data/processed/thesis_50_multiagent.json
    python scripts/run_invest_validation.py --no-meta-prompter --output data/processed/thesis_50_multiagent_nomp.json
    python scripts/run_invest_validation.py --limit 1 --output data/processed/smoke.json
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any, Dict, Optional

from llm_common import (CRITERIA, LLMClient, append_run_log, load_json, parse_verdicts,
                        prompt_hash, save_json)

SCRIPT_VERSION = "2.0.0"

# ---------------------------------------------------------------------------
# Agent prompts: identical to the first production run.
# ---------------------------------------------------------------------------
META_PROMPTER_SYSTEM = """You are a Lead Requirements Engineer and Meta-Prompter.
Your task is to analyze the domain context of a given software requirement and generate specific evaluation guardrails for auditing it against the INVEST criteria.
"""

DRAFTER_SYSTEM = """You are an Expert Requirements Quality Auditor (Drafter Agent).
Conduct an in-depth initial review of a given software requirement against the 6 INVEST criteria.
"""

REVIEWER_SYSTEM = """You are a Senior Quality Assurance Architect (Reviewer Agent).
Critically review the initial analysis generated by the Drafter Agent and deliver a balanced consensus review.
"""

AGGREGATOR_SYSTEM = """You are an Evaluator-Aggregator Agent.
Synthesize the Drafter's assessment and Reviewer's critique into a finalized verdict.
You MUST output strictly formatted JSON conforming to the requested schema, ensuring all 6 criteria (independent, negotiable, valuable, estimable, small, testable) are present.
"""

# Ablation condition (RQ2): the same generic guardrails for every requirement,
# in place of the Meta-Prompter's requirement-specific ones.
STATIC_GUARDRAILS = """Apply the standard INVEST definitions:
- Independent: the requirement can be developed, tested, and delivered without depending on other requirements being completed first.
- Negotiable: the requirement describes what is needed, not a fixed implementation, leaving room for discussion of how to satisfy it.
- Valuable: the requirement delivers clear value to an end user or other stakeholder, not just to the system's internal structure.
- Estimable: the requirement is specific and complete enough that a development team could reasonably estimate the effort to implement it.
- Small: the requirement is scoped narrowly enough to be completed within a single short development iteration, not a multi-feature epic.
- Testable: the requirement states or implies a clear, objective way to verify it has been satisfied.
"""

AGGREGATOR_TEMPLATE = """Requirement ID: {req_id}
Requirement Text: {text}

Drafter Assessment:
{draft}

Reviewer Critique:
{critique}

Synthesize the final evaluation across all 6 INVEST criteria.
Respond ONLY with a valid JSON object matching this schema structure:
{{
  "requirement_id": "{req_id}",
  "independent": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "negotiable": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "valuable": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "estimable": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "small": {{"passed": true, "rationale": "...", "recommendation": "..."}},
  "testable": {{"passed": true, "rationale": "...", "recommendation": "..."}}
}}
"""


class MultiAgentInvestPipeline:
    def __init__(self, llm: LLMClient, use_meta_prompter: bool = True):
        self.llm = llm
        self.use_meta_prompter = use_meta_prompter

    def validate_requirement(self, req: Dict[str, Any]) -> Dict[str, Any]:
        req_id = req.get("id", req.get("requirement_id", "UNKNOWN"))
        text = req.get("text_clean", req.get("text", ""))
        domain = req.get("domain", "General Software Engineering")
        stops = {}

        if self.use_meta_prompter:
            r = self.llm.ask(META_PROMPTER_SYSTEM,
                             f"Requirement ID: {req_id}\nDomain Context: {domain}\nRequirement Text: {text}\n\n"
                             "Generate domain-tailored evaluation guardrails.", 2048)
            guardrails, stops["meta_prompter"] = r["text"], r["stop_reason"]
        else:
            guardrails, stops["meta_prompter"] = STATIC_GUARDRAILS, "static"

        r = self.llm.ask(DRAFTER_SYSTEM,
                         f"Requirement ID: {req_id}\nRequirement Text: {text}\n\nDomain Guardrails:\n{guardrails}\n\n"
                         "Provide initial INVEST audit.", 4096)
        draft, stops["drafter"] = r["text"], r["stop_reason"]

        r = self.llm.ask(REVIEWER_SYSTEM,
                         f"Requirement ID: {req_id}\nRequirement Text: {text}\n\nDrafter Assessment:\n{draft}\n\n"
                         "Critique and refine.", 4096)
        critique, stops["reviewer"] = r["text"], r["stop_reason"]

        r = self.llm.ask(AGGREGATOR_SYSTEM,
                         AGGREGATOR_TEMPLATE.format(req_id=req_id, text=text, draft=draft, critique=critique), 4096)
        stops["aggregator"] = r["stop_reason"]
        parsed = parse_verdicts(r["text"], req_id)

        out = dict(req)
        out["invest_validation"] = parsed["verdicts"]
        out["agent_traces"] = {"meta_guardrails": guardrails, "drafter_notes": draft,
                               "reviewer_notes": critique, "aggregator_raw": r["text"]}
        out["run_meta"] = {"status": "ok" if not parsed["missing_criteria"] else "incomplete",
                           "missing_criteria": parsed["missing_criteria"], "stop_reasons": stops}
        return out


def main() -> None:
    p = argparse.ArgumentParser(description="Multi-agent INVEST review pipeline")
    p.add_argument("--input", default="data/processed/thesis_50_requirements.json")
    p.add_argument("--output", default="data/processed/thesis_50_multiagent.json")
    p.add_argument("--model", default="claude-sonnet-5")
    p.add_argument("--temperature", type=float, default=None,
                   help="e.g. 0 for near-deterministic runs; omitted = API default")
    p.add_argument("--no-meta-prompter", action="store_true", help="RQ2 ablation: static guardrails")
    p.add_argument("--limit", type=int, default=None)
    args = p.parse_args()

    in_path, out_path = Path(args.input), Path(args.output)
    if in_path.resolve() == out_path.resolve():
        raise SystemExit("--output must differ from --input (the input file must never be overwritten).")
    if not in_path.exists():
        raise SystemExit(f"Input file {in_path} not found.")

    data = load_json(in_path)[: args.limit] if args.limit else load_json(in_path)
    condition = "multi_agent_no_meta_prompter" if args.no_meta_prompter else "multi_agent"
    llm = LLMClient(args.model, args.temperature)
    pipeline = MultiAgentInvestPipeline(llm, use_meta_prompter=not args.no_meta_prompter)

    print(f"Condition: {condition} | model {args.model} | temperature {args.temperature} | {len(data)} requirements")
    results, failed = [], []
    for i, req in enumerate(data, 1):
        rid = req.get("id", f"REQ_{i}")
        print(f"[{i}/{len(data)}] {rid} ...", end=" ", flush=True)
        try:
            res = pipeline.validate_requirement(req)
            print(res["run_meta"]["status"] + (f" (missing: {res['run_meta']['missing_criteria']})"
                                               if res["run_meta"]["missing_criteria"] else ""))
        except Exception as exc:
            print(f"FAILED: {exc}")
            failed.append(rid)
            res = dict(req)
            res["invest_validation"] = {c: None for c in CRITERIA}
            res["run_meta"] = {"status": "failed", "error": str(exc)}
        results.append(res)
        save_json(out_path, results)  # save as we go, so a crash loses nothing

    incomplete = [r["id"] for r in results if r["run_meta"]["status"] == "incomplete"]
    append_run_log({
        "script": "run_invest_validation", "script_version": SCRIPT_VERSION, "condition": condition,
        "model": args.model, "temperature": args.temperature,
        "prompt_hash": prompt_hash(META_PROMPTER_SYSTEM, DRAFTER_SYSTEM, REVIEWER_SYSTEM, AGGREGATOR_SYSTEM,
                                   AGGREGATOR_TEMPLATE, STATIC_GUARDRAILS),
        "input": str(in_path), "output": str(out_path), "records": len(results),
        "failed": failed, "incomplete": incomplete, "api_calls": llm.calls,
        "input_tokens": llm.input_tokens, "output_tokens": llm.output_tokens,
    })
    print(f"\nSaved {out_path} | failed {len(failed)} | incomplete {len(incomplete)} | "
          f"calls {llm.calls} | tokens in {llm.input_tokens:,} / out {llm.output_tokens:,}")


if __name__ == "__main__":
    main()
